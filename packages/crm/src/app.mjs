const recordParents = recordKinds.map(kind => mimeTypes[kind])

/** `spec.creatables`: what the platform "New" menu offers, and where. All are proposed by the create script. */
export const creatables = allKinds.map(kind => {
  const entity = entities[kind]
  const folder = childFolders[kind]
  return {
    id: kind, 'display-name': entity.singular, description: `A new CRM ${entity.singular.toLowerCase()}`,
    icon: entity.icon, mime: mimeTypes[kind],
    // Records sit in their container; communications and notes beneath any record, or in its child folder.
    parents: entity.container ? [containers[entity.container].mime] : recordParents,
    'folder-names': entity.container ? entity.folderNames : [folder],
    // The script names the node: the next code for records, a UTC stamp for children.
    script: `./${createScript}`,
    template: `./templates/${kind}.json`,
  }
})

/** `spec.install`: managed app files under the install root, plus seeded (install-once, kept) data nodes. */
export const install = [
  { from: 'canvas/*.form.yaml', to: `${installRoot}/canvas/`, mode: 'managed', mime: 'application/vnd.verentis.canvas.form+yaml' },
  { from: 'canvas/*.page.yaml', to: `${installRoot}/canvas/`, mode: 'managed', mime: 'application/vnd.verentis.canvas.page+yaml' },
  { from: 'schemas/*.schema.json', to: `${installRoot}/schemas/`, mode: 'managed', mime: 'application/schema+json' },
  // Explicit MIME so placeholder templates are never classified as CRM records by their $schema.
  { from: 'templates/*.json', to: `${installRoot}/templates/`, mode: 'managed', mime: 'application/json' },
  ...Object.entries(containers).map(([name, container]) => ({ from: `seed/${name}`, to: container.path, mode: 'seed', mime: container.mime })),
  { from: 'seed/settings.json', to: settingsPath, mode: 'seed', mime: mimeTypes.settings },
]

