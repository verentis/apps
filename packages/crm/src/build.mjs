// Generates the CRM package outputs: manifest, Canvas documents, JSON Schemas, templates and seeds.
// `--check` fails instead of writing when an output is stale.
import { mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { containers, defaultSettings, schemas, templates } from './contracts.mjs'
import { createScriptConsent, createScriptManifest, manifest, featureOverlay, productionOverlay, scriptConfig } from './app.mjs'
import { buildPages, documentFileAccess } from './pages.mjs'

const root = new URL('../', import.meta.url)
const check = process.argv.includes('--check')
const json = value => `${JSON.stringify(value, null, 2)}\n`

const pages = buildPages()
const outputs = {
  'crm.app.yaml': json({
    ...manifest, spec: { ...manifest.spec, 'file-access': [...documentFileAccess(pages), ...createScriptConsent] },
  }),
  'environments/feature.yaml': json(featureOverlay),
  'environments/production.yaml': json(productionOverlay),
  'seed/settings.json': json(defaultSettings),
  ...Object.fromEntries(Object.entries(containers).map(([name, container]) => [`seed/${name}`, ''])),
  ...Object.fromEntries(Object.entries(schemas).map(([name, schema]) => [`schemas/${name}.schema.json`, json(schema)])),
  ...Object.fromEntries(Object.entries(templates).map(([name, template]) => [`templates/${name}.json`, json(template)])),
  ...Object.fromEntries(Object.entries(pages).map(([name, document]) => [`canvas/${name}`, json(document)])),
  'scripts/create/manifest.yaml': createScriptManifest,
  'scripts/create/config.mjs': `// Generated by src/build.mjs from the CRM contracts. Do not edit.\nexport default ${JSON.stringify(scriptConfig, null, 2)}\n`,
}
// Hand-written files in generated directories.
const sources = new Set(['scripts/create/main.mjs', 'scripts/create/propose.mjs'])

const stale = []
for (const directory of ['canvas', 'schemas', 'templates', 'seed', 'scripts/create']) {
  const existing = await readdir(new URL(`${directory}/`, root)).catch(() => [])
  for (const name of existing) {
    if (!(`${directory}/${name}` in outputs) && !sources.has(`${directory}/${name}`)) stale.push(`${directory}/${name}`)
  }
}

for (const [path, content] of Object.entries(outputs)) {
  const file = new URL(path, root)
  if (check) {
    const current = await readFile(file, 'utf8').catch(() => null)
    if (current !== content) stale.push(path)
  } else {
    await mkdir(new URL('./', file), { recursive: true })
    await writeFile(file, content)
  }
}

if (check) {
  if (stale.length) throw new Error(`Generated CRM outputs are stale: ${stale.join(', ')}`)
} else {
  for (const path of stale) await rm(new URL(path, root))
}
console.log(`${check ? 'Checked' : 'Generated'} ${Object.keys(outputs).length} CRM outputs in ${fileURLToPath(root)}`)
