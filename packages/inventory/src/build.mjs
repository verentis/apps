// Generates the Inventory package outputs: manifest, Canvas documents, JSON Schemas, templates, seeds and the
// generated parts of the scripts. `--check` fails instead of writing when an output is stale.
import { apiContract, generate, json, scriptManifest, sharedSource } from '../../../tools/file-apps/build.mjs'
import { documentFileAccess } from '../../../tools/file-apps/canvas.mjs'
import { containers, defaultSettings, mimeTypes, schemaId, schemas, settingsPath, starterRecords, templates } from './contracts.mjs'
import {
  apiScriptFileAccess, apiScriptName, createScriptConfig, createScriptFileAccess, createScriptName, manifest, postScriptFileAccess, postScriptName,
  featureOverlay, productionOverlay, scriptConsents,
} from './app.mjs'
import { buildPages } from './pages.mjs'

const pages = buildPages()
const api = await apiContract(new URL('../', import.meta.url))

await generate({
  root: new URL('../', import.meta.url),
  label: 'Inventory',
  outputs: {
    'inventory.app.yaml': json({ ...manifest, spec: { ...manifest.spec, 'file-access': [...documentFileAccess(pages), ...scriptConsents], ...(api ? { api } : {}) } }),
    'environments/feature.yaml': json(featureOverlay),
    'environments/production.yaml': json(productionOverlay),
    'seed/settings.json': json(defaultSettings),
    ...Object.fromEntries(Object.keys(containers).map(name => [`seed/${name}`, ''])),
    ...Object.fromEntries(starterRecords.map(record => [`seed/starter/${record.code}.json`, json(record)])),
    ...Object.fromEntries(Object.entries(schemas).map(([name, schema]) => [`schemas/${name}.schema.json`, json(schema)])),
    ...Object.fromEntries(Object.entries(templates).map(([name, template]) => [`templates/${name}.json`, json(template)])),
    ...Object.fromEntries(Object.entries(pages).map(([name, document]) => [`canvas/${name}`, json(document)])),
    'scripts/create/manifest.yaml': scriptManifest(createScriptName, createScriptFileAccess,
      'New records are written create-only into the Inventory containers.'),
    'scripts/create/config.mjs': `// Generated by src/build.mjs from the Inventory contracts. Do not edit.\nexport default ${JSON.stringify(createScriptConfig, null, 2)}\n`,
    'scripts/create/main.mjs': await sharedSource('create/main.mjs'),
    'scripts/create/propose.mjs': await sharedSource('create/propose.mjs'),
    'scripts/post/manifest.yaml': scriptManifest(postScriptName, postScriptFileAccess,
      'Posting validates against products and warehouses and writes moves and adjustments conditionally.'),
    'scripts/post/ledger.mjs': await sharedSource('ledger.mjs'),
    'scripts/api/manifest.yaml': scriptManifest(apiScriptName, apiScriptFileAccess,
      'The operations other apps call through the platform (api.yaml); moves are written create-only.'),
    'scripts/api/runtime.mjs': await sharedSource('api/runtime.mjs'),
    'scripts/api/config.mjs': `// Generated by src/build.mjs from the Inventory contracts. Do not edit.\nexport default ${JSON.stringify({
      moves: containers.moves.path, mime: mimeTypes.move, schema: schemaId('move'), settingsPath,
    }, null, 2)}\n`,
  },
  directories: ['canvas', 'schemas', 'templates', 'seed', 'seed/starter', 'scripts', 'scripts/create', 'scripts/post', 'scripts/api'],
  sources: ['scripts/post/main.mjs', 'scripts/api/main.mjs'],
})
