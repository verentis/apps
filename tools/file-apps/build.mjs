// Shared generator for the file-based Accounting and Invoicing packages: writes every output, removes stale files
// in generated directories, and with `--check` fails instead of writing when an output is stale.
import { mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { parse as parseYaml } from 'yaml'
import { usesUserProfile } from './canvas.mjs'

export const json = value => `${JSON.stringify(value, null, 2)}\n`


const shared = new URL('./', import.meta.url)

/**
 * The package's API contract (`api.yaml` beside `src/`) as the manifest's `spec.api`: the operations the app offers
 * other apps and agents, and those of other apps it uses. Absent file: no contract (`undefined`).
 */
export async function apiContract(root) {
  const text = await readFile(new URL('api.yaml', root), 'utf8').catch(() => null)
  if (text === null) return undefined
  const document = parseYaml(text)
  if (document?.kind !== 'Api' || typeof document.spec !== 'object') throw new Error('api.yaml must be a kind: Api document with a spec')
  return document.spec
}

/** A shared script source, stamped as generated so it is edited in tools/file-apps only. */
export async function sharedSource(path) {
  const content = await readFile(new URL(path, shared), 'utf8')
  return `// Generated by the package build from tools/file-apps/${path}. Do not edit.\n${content}`
}

const quote = value => JSON.stringify(value)

/** The ScriptRun manifest of a packaged nodejs script, with the file access it asks the installer for. */
export function scriptManifest(name, fileAccess, comment) {
  return [
    'api-version: verentis.io/v1',
    'kind: ScriptRun',
    'metadata:',
    `  id: ${name}`,
    'engine: nodejs',
    'runtime: server',
    'node-version: lts',
    'entry-point: main.mjs',
    'resources:',
    '  size: small',
    `# Generated by src/build.mjs. ${comment}`,
    'file-access:',
    ...fileAccess.flatMap(grant => [
      `  - path: ${quote(grant.path)}`,
      `    mode: ${grant.mode}`,
      `    reason: ${quote(grant.reason)}`,
    ]),
    '',
  ].join('\n')
}

/** Install consent entries for a script; `verentis pack` adds the same entries (deduplicated). */
export const scriptConsent = (name, fileAccess) => fileAccess.map(grant => ({ ...grant, origin: { kind: 'script', id: name } }))

/**
 * An app whose own unregistered pages read the signed-in user's email or roles declares `user-profile` on its
 * manifest, so the install consent shows it and the host shares them (registered pages declare it themselves).
 * `pages` are the app's Canvas documents; returns the manifest, with the capability added when needed.
 */
export function withUserProfile(manifest, pages) {
  const needed = Object.values(pages).some(document => document?.spec && !document.spec.binds?.length && usesUserProfile(document.spec))
  const capabilities = manifest.spec.capabilities ?? []
  if (!needed || capabilities.includes('user-profile')) return manifest
  return { ...manifest, spec: { ...manifest.spec, capabilities: [...capabilities, 'user-profile'] } }
}

/** `withUserProfile` over the generated outputs: the `canvas/*.yaml` documents and the `*.app.yaml` manifest. */
function declareUserProfile(outputs) {
  const parse = content => { try { return JSON.parse(content) } catch { return null } }
  const pages = Object.entries(outputs).filter(([path]) => /^canvas\/[^/]+\.yaml$/.test(path)).map(([, content]) => parse(content))
  return Object.fromEntries(Object.entries(outputs).map(([path, content]) => {
    const manifest = /^[^/]+\.app\.yaml$/.test(path) ? parse(content) : null
    if (!manifest?.spec) return [path, content]
    const declared = withUserProfile(manifest, pages)
    return [path, declared === manifest ? content : json(declared)]
  }))
}

export async function generate({ root, label, outputs: given, directories, sources = [] }) {
  const outputs = declareUserProfile(given)
  const check = process.argv.includes('--check')
  const kept = new Set(sources)
  const stale = []
  for (const directory of directories) {
    const existing = await readdir(new URL(`${directory}/`, root)).catch(() => [])
    for (const name of existing) {
      const path = `${directory}/${name}`
      if (!(path in outputs) && !kept.has(path) && !directories.includes(path)) stale.push(path)
    }
  }
  for (const [path, content] of Object.entries(outputs)) {
    const file = new URL(path, root)
    if (check) {
      const current = await readFile(file, 'utf8').catch(() => null)
      if (current !== content) stale.push(path)
    } else {
      await mkdir(new URL('./', file), { recursive: true })
      await writeFile(file, content)
    }
  }
  if (check) {
    if (stale.length) throw new Error(`Generated ${label} outputs are stale: ${stale.join(', ')}`)
  } else {
    for (const path of stale) await rm(new URL(path, root), { recursive: true })
  }
  console.log(`${check ? 'Checked' : 'Generated'} ${Object.keys(outputs).length} ${label} outputs in ${fileURLToPath(root)}`)
}
