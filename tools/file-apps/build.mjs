// Shared generator for the file-based Accounting and Invoicing packages: writes every output, removes stale files
// in generated directories, and with `--check` fails instead of writing when an output is stale.
import { mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

export const json = value => `${JSON.stringify(value, null, 2)}\n`

const shared = new URL('./', import.meta.url)

/** A shared script source, stamped as generated so it is edited in tools/file-apps only. */
export async function sharedSource(path) {
  const content = await readFile(new URL(path, shared), 'utf8')
  return `// Generated by the package build from tools/file-apps/${path}. Do not edit.\n${content}`
}

const quote = value => JSON.stringify(value)

/** The ScriptRun manifest of a packaged nodejs script, with the file access it asks the installer for. */
export function scriptManifest(name, fileAccess, comment) {
  return [
    'api-version: verentis.io/v1',
    'kind: ScriptRun',
    'metadata:',
    `  id: ${name}`,
    'engine: nodejs',
    'runtime: server',
    'node-version: lts',
    'entry-point: main.mjs',
    'resources:',
    '  size: small',
    `# Generated by src/build.mjs. ${comment}`,
    'file-access:',
    ...fileAccess.flatMap(grant => [
      `  - path: ${quote(grant.path)}`,
      `    mode: ${grant.mode}`,
      `    reason: ${quote(grant.reason)}`,
    ]),
    '',
  ].join('\n')
}

/** Install consent entries for a script; `verentis pack` adds the same entries (deduplicated). */
export const scriptConsent = (name, fileAccess) => fileAccess.map(grant => ({ ...grant, origin: { kind: 'script', id: name } }))

export async function generate({ root, label, outputs, directories, sources = [] }) {
  const check = process.argv.includes('--check')
  const kept = new Set(sources)
  const stale = []
  for (const directory of directories) {
    const existing = await readdir(new URL(`${directory}/`, root)).catch(() => [])
    for (const name of existing) {
      const path = `${directory}/${name}`
      if (!(path in outputs) && !kept.has(path) && !directories.includes(path)) stale.push(path)
    }
  }
  for (const [path, content] of Object.entries(outputs)) {
    const file = new URL(path, root)
    if (check) {
      const current = await readFile(file, 'utf8').catch(() => null)
      if (current !== content) stale.push(path)
    } else {
      await mkdir(new URL('./', file), { recursive: true })
      await writeFile(file, content)
    }
  }
  if (check) {
    if (stale.length) throw new Error(`Generated ${label} outputs are stale: ${stale.join(', ')}`)
  } else {
    for (const path of stale) await rm(new URL(path, root), { recursive: true })
  }
  console.log(`${check ? 'Checked' : 'Generated'} ${Object.keys(outputs).length} ${label} outputs in ${fileURLToPath(root)}`)
}
